import * as fs from 'fs';
import * as path from 'path';

const isWindows = process.platform === 'win32';

function ninjaEscape(value: string): string {
	return value.replace(/\$/g, '$$$$').replace(/\n/g, '$\n');
}

function ninjaPath(value: string): string {
	return value.replace(/[$ :\n]/g, '$$$&');
}

function shellArg(arg: string): string {
	if (/^[\w@%+=:,./-]+$/.test(arg)) {
		return arg;
	}
	if (isWindows) {
		return `"${arg.replace(/(\\*)"/g, '$1$1\\"').replace(/(\\+)$/, '$1$1')}"`;
	}
	return `'${arg.replace(/'/g, `'\\''`)}'`;
}

function shellArgs(args: string[]): string {
	return ninjaEscape(args.map(shellArg).join(' '));
}

function pad(value: number): string {
	return String(value).padStart(2, '0');
}

function generateStubs(project: string): string {
	const now = new Date();
	const timestamp = `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())} ${pad(now.getHours())}:${pad(now.getMinutes())}:${pad(now.getSeconds())}`;
	const directory = project.length > 29 ? `~${project.slice(-28)}` : project;
	return `/*
 * Generated by Bromine Sim; do not edit.
 */

#include <filesystem>

namespace bromine
{

const std::filesystem::path &getProjectPath()
{
    static const std::filesystem::path path = u8${JSON.stringify(project)};
    return path;
}

}

extern "C" char const* const _PROS_COMPILE_TIMESTAMP = ${JSON.stringify(timestamp)};
extern "C" char const* const _PROS_COMPILE_DIRECTORY = ${JSON.stringify(directory)};
extern "C" const int _PROS_COMPILE_TIMESTAMP_INT = ${Math.floor(now.getTime() / 1000)};
`;
}

function getLinkArgs(coreDir: string, llemu: boolean): string[] {
	const lib = (name: string) => path.join(coreDir, 'lib', `lib${name}.a`);
	const wholeArchives = [lib('bromine-sim-core'), ...(llemu ? [lib('lvgl')] : [])];
	const archives = [lib('raylib'), lib('box2d')];
	if (process.platform === 'darwin') {
		return [
			...wholeArchives.map(archive => `-Wl,-force_load,${archive}`),
			...archives,
			'-framework', 'IOKit', '-framework', 'Cocoa', '-framework', 'OpenGL',
		];
	}
	return [
		'-Wl,--whole-archive', ...wholeArchives, '-Wl,--no-whole-archive',
		...archives,
		...(isWindows ? ['-lwinmm', '-lgdi32', '-lopengl32'] : ['-lm', '-lpthread', '-ldl', '-lX11']),
	];
}

async function findSources(srcDir: string): Promise<string[]> {
	if (!fs.existsSync(srcDir)) {
		return [];
	}
	const entries = await fs.promises.readdir(srcDir, { recursive: true });
	return entries.filter(entry => /\.(c|cpp)$/.test(entry)).sort();
}

interface SourceDir {
	srcDir: string;
	objDir: string;
	exclude?: string[];
}

export async function writeBuildFiles(project: string, buildDir: string, zig: string, coreDir: string, templateDirs: { name: string; dir: string }[]): Promise<string> {
	await fs.promises.mkdir(buildDir, { recursive: true });

	const stubs = path.join(buildDir, 'stubs.cpp');
	await fs.promises.writeFile(stubs, generateStubs(project));

	const includeDir = path.join(project, 'include');
	const llemu = fs.existsSync(path.join(includeDir, 'liblvgl', 'llemu.hpp'));
	const cflags = [
		'-g',
		'-DBROMINE_SIM=1',
		'-DFMT_CONSTEVAL=',
		...(llemu ? ['-D_PROS_INCLUDE_LIBLVGL_LLEMU_H', '-D_PROS_INCLUDE_LIBLVGL_LLEMU_HPP'] : []),
		'-include', path.join(coreDir, 'include', 'newlib_compat.h'),
		'-I', path.join(coreDir, 'include'),
		'-I', includeDir,
	];
	const libs = getLinkArgs(coreDir, llemu);
	const exe = path.join(buildDir, isWindows ? 'sim.exe' : 'sim');

	const lines = [
		`zig = ${shellArgs([zig])}`,
		`cflags = ${shellArgs(cflags)}`,
		'',
		'rule cc',
		'  command = $zig cc -std=gnu23 $cflags $iquote -MD -MF $out.d -c $in -o $out',
		'  description = Compiling $in',
		'  depfile = $out.d',
		'  deps = gcc',
		'',
		'rule cxx',
		'  command = $zig c++ -std=gnu++23 $cflags $iquote -MD -MF $out.d -c $in -o $out',
		'  description = Compiling $in',
		'  depfile = $out.d',
		'  deps = gcc',
		'',
		'rule link',
		'  command = $zig c++ $in $libs -o $out',
		'  description = Linking $out',
		'',
	];

	const sourceDirs: SourceDir[] = [
		{ srcDir: path.join(project, 'src'), objDir: 'obj' },
		...templateDirs.map(({ name, dir }) => ({ srcDir: path.join(dir, 'src'), objDir: `obj/templates/${name}`, exclude: ['main.cpp'] })),
	];
	const objects: string[] = [];
	for (const { srcDir, objDir, exclude } of sourceDirs) {
		for (const source of await findSources(srcDir)) {
			if (exclude?.includes(path.basename(source))) {
				continue;
			}
			const object = `${objDir}/${source.split(path.sep).join('/')}.o`;
			const rule = source.endsWith('.c') ? 'cc' : 'cxx';
			lines.push(
				`build ${ninjaPath(object)}: ${rule} ${ninjaPath(path.join(srcDir, source))}`,
				`  iquote = ${shellArgs(['-iquote', path.join(includeDir, path.dirname(source))])}`,
			);
			objects.push(object);
		}
	}

	lines.push(`build obj/stubs.cpp.o: cxx ${ninjaPath(stubs)}`);
	objects.push('obj/stubs.cpp.o');

	const coreLibs = ['bromine-sim-core', 'lvgl', 'raylib', 'box2d'].map(name => path.join(coreDir, 'lib', `lib${name}.a`));
	lines.push(
		`build ${ninjaPath(exe)}: link ${objects.map(ninjaPath).join(' ')} | ${coreLibs.map(ninjaPath).join(' ')}`,
		`  libs = ${shellArgs(libs)}`,
		'',
	);

	await fs.promises.writeFile(path.join(buildDir, 'build.ninja'), lines.join('\n'));
	return exe;
}
